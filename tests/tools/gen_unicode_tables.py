#!/usr/bin/env python3
# Regenerates src/loader/unicode_tables.inc: code point ranges for the Unicode categories the BPE pre-tokenizer
# regexes use (\p{L}, \p{M}, \p{N}) and White_Space (\s). Python's unicodedata supplies the data.
#   python3 -I tests/tools/gen_unicode_tables.py > src/loader/unicode_tables.inc
import sys, unicodedata

def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev)); start = None
    if start is not None:
        out.append((start, prev))
    return out

def emit(name, rs):
    print("static const uint32_t %s[][2] = {" % name)
    line = "\t"
    for a, b in rs:
        item = "{ 0x%X, 0x%X }, " % (a, b)
        if len(line) + len(item) > 120:
            print(line.rstrip()); line = "\t"
        line += item
    print(line.rstrip())
    print("};")

print("// Generated by tests/tools/gen_unicode_tables.py (Unicode %s). Do not edit." % unicodedata.unidata_version)
emit("kUnicodeLetter", ranges(lambda c: unicodedata.category(chr(c))[0] == "L"))
emit("kUnicodeMark", ranges(lambda c: unicodedata.category(chr(c))[0] == "M"))
emit("kUnicodeNumber", ranges(lambda c: unicodedata.category(chr(c))[0] == "N"))
WS = {0x9, 0xA, 0xB, 0xC, 0xD, 0x20, 0x85, 0xA0, 0x1680, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000} | set(range(0x2000, 0x200B))
emit("kUnicodeSpace", ranges(lambda c: c in WS))

# ---- NFC (Qwen's tokenizer.json normalizer): full canonical decompositions, combining classes, primary composites
def nfd_of(cp):
    return [ord(c) for c in unicodedata.normalize("NFD", chr(cp))]

def is_hangul_syllable(cp):
    return 0xAC00 <= cp <= 0xD7A3

dec = [(cp, nfd_of(cp)) for cp in range(0x110000) if not is_hangul_syllable(cp) and nfd_of(cp) != [cp]]
print("static const uint32_t kNfdData[] = {")
data, index, off = [], [], 0
for cp, seq in dec:
    index.append((cp, off, len(seq)))
    data.extend(seq)
    off += len(seq)
line = "\t"
for v in data:
    item = "0x%X, " % v
    if len(line) + len(item) > 120:
        print(line.rstrip()); line = "\t"
    line += item
print(line.rstrip()); print("};")
print("static const uint32_t kNfdIndex[][3] = {")
line = "\t"
for cp, o, n in index:
    item = "{ 0x%X, %d, %d }, " % (cp, o, n)
    if len(line) + len(item) > 120:
        print(line.rstrip()); line = "\t"
    line += item
print(line.rstrip()); print("};")

ccc_ranges, start, prev, cur = [], None, None, 0
for cp in range(0x110000):
    c = unicodedata.combining(chr(cp))
    if c == cur and start is not None and cp == prev + 1 and c != 0:
        prev = cp
        continue
    if start is not None and cur != 0:
        ccc_ranges.append((start, prev, cur))
    start, prev, cur = (cp, cp, c) if c != 0 else (None, None, 0)
if start is not None and cur != 0:
    ccc_ranges.append((start, prev, cur))
print("static const uint32_t kCombiningClass[][3] = {")
line = "\t"
for a, b, c in ccc_ranges:
    item = "{ 0x%X, 0x%X, %d }, " % (a, b, c)
    if len(line) + len(item) > 120:
        print(line.rstrip()); line = "\t"
    line += item
print(line.rstrip()); print("};")

pairs = []
for cp in range(0x110000):
    if is_hangul_syllable(cp):
        continue
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
        pairs.append((parts[0], parts[1], cp))
pairs.sort()
print("static const uint32_t kComposePairs[][3] = {")
line = "\t"
for a, b, c in pairs:
    item = "{ 0x%X, 0x%X, 0x%X }, " % (a, b, c)
    if len(line) + len(item) > 120:
        print(line.rstrip()); line = "\t"
    line += item
print(line.rstrip()); print("};")
