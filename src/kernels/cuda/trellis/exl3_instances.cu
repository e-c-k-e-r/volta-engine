// Stub out bitwidth 1 for the 3inst and mcg codebooks to avoid hundreds of unused template instantiations (1 bit with mul1 is real: the
// DeepSeek-V4.1 SAGE packs have 1-bit experts; 7 and 8 are real too: Flash-Next ships 8 bpw projections)
#define STUB_K(K) \
	fp_exl3_gemm_kernel tfp_exl3_gemm_kernel_fp32_b##K##_cb0[5] = {}; \
	fp_exl3_gemm_kernel tfp_exl3_gemm_kernel_fp16_b##K##_cb0[5] = {}; \
	fp_exl3_mgemm_kernel tfp_exl3_mgemm_kernel_fp32_b##K##_cb0[5] = {}; \
	fp_exl3_mgemm_kernel tfp_exl3_mgemm_kernel_fp16_b##K##_cb0[5] = {}; \
	fp_exl3_gemm_kernel tfp_exl3_gemm_kernel_fp32_b##K##_cb1[5] = {}; \
	fp_exl3_gemm_kernel tfp_exl3_gemm_kernel_fp16_b##K##_cb1[5] = {}; \
	fp_exl3_mgemm_kernel tfp_exl3_mgemm_kernel_fp32_b##K##_cb1[5] = {}; \
	fp_exl3_mgemm_kernel tfp_exl3_mgemm_kernel_fp16_b##K##_cb1[5] = {};

STUB_K(1)
#undef STUB_K

// The real instantiations (bit widths 2 to 8, codebooks 0 to 2) are one translation unit each (exl3_instance_unit.cu.in, generated by CMake)
// so they compile in parallel. A codebook left out of ENGINE_EXL3_CODEBOOKS gets empty tables here, like bit width 1 above
#define STUB_KCB(K, cb) \
	fp_exl3_gemm_kernel tfp_exl3_gemm_kernel_fp32_b##K##_cb##cb[5] = {}; \
	fp_exl3_gemm_kernel tfp_exl3_gemm_kernel_fp16_b##K##_cb##cb[5] = {}; \
	fp_exl3_mgemm_kernel tfp_exl3_mgemm_kernel_fp32_b##K##_cb##cb[5] = {}; \
	fp_exl3_mgemm_kernel tfp_exl3_mgemm_kernel_fp16_b##K##_cb##cb[5] = {};
#define STUB_CB(cb) STUB_KCB(2, cb) STUB_KCB(3, cb) STUB_KCB(4, cb) STUB_KCB(5, cb) STUB_KCB(6, cb) STUB_KCB(7, cb) STUB_KCB(8, cb)
#if defined(EXL3_CB_BUILT_0) && !EXL3_CB_BUILT_0
STUB_CB(0)
#endif
#if defined(EXL3_CB_BUILT_1) && !EXL3_CB_BUILT_1
STUB_CB(1)
#endif
#if defined(EXL3_CB_BUILT_2) && !EXL3_CB_BUILT_2
STUB_CB(2)
#endif
#undef STUB_CB
#undef STUB_KCB
#if defined(EXL3_CB_BUILT_2) && !EXL3_CB_BUILT_2
fp_exl3_gemm_kernel tfp_exl3_gemm_kernel_fp32_b1_cb2[5] = {};
fp_exl3_gemm_kernel tfp_exl3_gemm_kernel_fp16_b1_cb2[5] = {};
fp_exl3_mgemm_kernel tfp_exl3_mgemm_kernel_fp32_b1_cb2[5] = {};
fp_exl3_mgemm_kernel tfp_exl3_mgemm_kernel_fp16_b1_cb2[5] = {};
#endif

