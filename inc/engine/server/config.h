#pragma once

#include <string>
#include <vector>

namespace engine::server {

// MiniMax-H3 (video + audio generation) settings; used when the checkpoint directory is an H3 pipeline (model_type "minimax_h3")
struct VideoConfig {
	std::string dit;                    // Comfy INT8 ConvRot transformer checkpoint of the FL2VA partition (text, keyframes)
	std::string dit_ref2va;             // the Ref2VA partition (references); empty = no reference tasks
	std::vector<std::string> lora_dirs; // directories scanned for adapters (turbo and community LoRAs)
	std::string out_dir = "h3_jobs";    // job history and results
	std::vector<int> devices;           // GPUs of the DiT (sequence parallel); empty = the first tp_size GPUs
	int max_rows = 36000;               // largest packed sequence a job may need (text + references + audio + video rows)
	bool resident = true;               // keep the transformer on the GPUs between jobs (off: load it for each job, free it after)
	int resident_idle_s = 0;            // with resident: free it after this many idle seconds (0 = never)
	bool tensor_parallel = false;       // shard the transformer over the GPUs by heads / MLP width (a quarter of the weights each) instead of by rows (needs NCCL)
};

struct ServerConfig {
	std::string host = "0.0.0.0";
	int port = 8000;
	int max_batch_size = 8;
	int request_timeout_s = 30;   // a connection that sends nothing for this long before its request is complete is dropped
	int default_max_tokens = 256;
	// Sampling defaults for requests that do not set them; negative = take the checkpoint's generation_config.json
	// (temperature, top_p, top_k), else greedy / 1.0 / 16.
	float default_temperature = -1.0f;
	float default_top_p = -1.0f;
	int default_top_k = -1;
	bool default_enable_thinking = false; // requests without an explicit setting (reasoning_effort / thinking enable it)

	std::string model_type;      // deduced by resolve() from <model_dir>/config.json (qwen3_5 | glm5_next)
	std::string model_dir;       // required
	std::string draft_model_dir; // required with use_speculation
	bool use_speculation = false;
	bool load_weights = true;
	bool benchmark_mode = false;
	int tp_size = 4;
	VideoConfig video;

	bool load_from_json( const char* json_path );
	// Parses --config and the CLI, then resolves and validates (model_dir, model_type, draft dir). Exits with status 2 on error.
	void parse_cli_args( int argc, char** argv );
	bool resolve();
};

// docs/CONFIG.md as generated by `volta_server --print-config-docs`
std::string server_config_markdown();

} // namespace engine::server
